<?php

namespace Drupal\dungeoncrawler_content\Service\EditorGm\Tool\Dungeon;

use Drupal\dungeoncrawler_content\Service\EditorGm\DungeonEditorGmToolContext;
use Drupal\dungeoncrawler_content\Service\EditorGm\EditorGmToolContext;
use Drupal\dungeoncrawler_content\Service\EditorGm\EditorGmToolDefinition;
use Drupal\dungeoncrawler_content\Service\EditorGm\EditorGmToolInterface;
use Drupal\dungeoncrawler_content\Service\Generation\CanonicalRoomBuildService;

/**
 * Builds and publishes the street room of a district through the Room Editor.
 *
 * A street is an open hex disc with no doors: the doors belong to the building
 * rooms, which overlay it. The disc is sized from the building count and
 * spacing so every building has clear space around it. Nothing is generated by
 * a model. The background art must be supplied; a street
 * without one cannot be published. The tool does not place the room.
 */
final class BuildDistrictStreetTool implements EditorGmToolInterface {

  private const DEFAULT_SPACING = 10;

  // Clear hexes between the outermost building site and the rim.
  private const RIM_MARGIN = 6;

  public function __construct(private readonly CanonicalRoomBuildService $rooms) {}

  public function definition(): EditorGmToolDefinition {
    return new EditorGmToolDefinition(
      'build_district_street',
      EditorGmToolDefinition::FAMILY_EXECUTION,
      'Create and publish the street room of a district (room_type street): an open hex disc with no door ports, sized from the building count, and its background art. The doors belong to the building rooms. Rooms are not definitions: use this, not the definition tools, to make a street. Afterwards set the dungeon kind to district, place the street, then use plan_district_buildings to put the buildings on it.',
      TRUE,
      'CanonicalRoomBuildService::buildStreet()',
      [
        EditorGmToolDefinition::argument('room_id', 'string', TRUE, 'Slug for the new street room, e.g. blackroot-village. Must not already exist.'),
        EditorGmToolDefinition::argument('name', 'string', TRUE, 'Display name of the street.'),
        EditorGmToolDefinition::argument('description', 'string', TRUE, 'What the street looks like.'),
        EditorGmToolDefinition::argument('building_count', 'integer', TRUE, 'How many buildings the street must hold; sizes the disc.'),
        EditorGmToolDefinition::argument('background_url', 'string', TRUE, 'URL of the street background art the party walks on.'),
        EditorGmToolDefinition::argument('background_width', 'integer', FALSE, 'Art width in pixels.'),
        EditorGmToolDefinition::argument('background_height', 'integer', FALSE, 'Art height in pixels.'),
        EditorGmToolDefinition::argument('spacing', 'integer', FALSE, 'Hexes between neighbouring buildings (default 10, minimum 6).'),
      ],
    );
  }

  public function execute(array $arguments, EditorGmToolContext $context): array {
    DungeonEditorGmToolContext::of($context);
    $room_id = EditorGmToolContext::requireString($arguments, 'room_id');
    $building_count = EditorGmToolContext::requireInt($arguments, 'building_count');
    if ($building_count < 1) {
      throw new \InvalidArgumentException('district_street_needs_buildings');
    }
    $spacing = isset($arguments['spacing']) ? EditorGmToolContext::requireInt($arguments, 'spacing') : self::DEFAULT_SPACING;
    if ($spacing < 6) {
      throw new \InvalidArgumentException('district_street_spacing_too_small');
    }
    $background = ['url' => EditorGmToolContext::requireString($arguments, 'background_url')];
    foreach (['width', 'height'] as $dimension) {
      if (isset($arguments['background_' . $dimension])) {
        $background[$dimension] = EditorGmToolContext::requireInt($arguments, 'background_' . $dimension);
      }
    }

    // Lattice points nearest the centre first: the smallest disc that holds
    // every building.
    $points = [];
    $reach = (int) ceil(sqrt($building_count)) + 1;
    for ($i = -$reach; $i <= $reach; $i++) {
      for ($j = -$reach; $j <= $reach; $j++) {
        $q = $i * $spacing;
        $r = $j * $spacing;
        $points[] = ['q' => $q, 'r' => $r, 'distance' => intdiv(abs($q) + abs($q + $r) + abs($r), 2)];
      }
    }
    usort($points, static fn(array $a, array $b): int => [$a['distance'], $a['q'], $a['r']] <=> [$b['distance'], $b['q'], $b['r']]);
    $sites = array_slice($points, 0, $building_count);
    $radius = max(array_column($sites, 'distance')) + self::RIM_MARGIN;

    $built = $this->rooms->buildStreet(
      $room_id,
      EditorGmToolContext::requireString($arguments, 'name'),
      mb_substr(EditorGmToolContext::requireString($arguments, 'description'), 0, 2000),
      $radius,
      $background,
      '1.0.0',
      'Street room of a district.',
    );

    return [
      'room_id' => $room_id,
      'version' => $built['version'],
      'radius' => $radius,
      'hexes' => count($built['room']['hexes'] ?? []),
      'next_step' => 'Set the dungeon kind to district, place this street room, then call plan_district_buildings.',
    ];
  }

}
